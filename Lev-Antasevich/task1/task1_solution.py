from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.metrics import accuracy_score, classification_report

X_train = train_df[feature_cols].copy()
y_train = train_df['prediction'].copy()
X_test = test_df[feature_cols].copy()

imputer = SimpleImputer(strategy='median')
X_train_imputed = imputer.fit_transform(X_train)
X_test_imputed = imputer.transform(X_test)

scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train_imputed)
X_test_scaled = scaler.transform(X_test_imputed)

X_train_split, X_val, y_train_split, y_val = train_test_split(
    X_train_scaled, y_train, test_size=0.2, random_state=42, stratify=y_train
)

print("Training Random Forest classifier...")
model = RandomForestClassifier(
    n_estimators=100,
    max_depth=10,
    random_state=42,
    class_weight='balanced'
)

model.fit(X_train_split, y_train_split)

val_predictions = model.predict(X_val)
val_accuracy = accuracy_score(y_val, val_predictions)
print(f"Validation accuracy: {val_accuracy:.4f}")
print("\nClassification report:")
print(classification_report(y_val, val_predictions))

print("\nRetraining on full training data...")
model.fit(X_train_scaled, y_train)
ml_predictions = model.predict(X_test_scaled)

ml_submission = pd.DataFrame({
    'patient_id': test_df['patient_id'],
    'prediction': ml_predictions
})

print(f"\nML prediction distribution:")
print(ml_submission['prediction'].value_counts())

ml_submission.to_csv('task1_predictions_ml.csv', index=False)
