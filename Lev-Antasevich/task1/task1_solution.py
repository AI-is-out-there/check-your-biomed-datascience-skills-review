import pandas as pd
import numpy as np
import warnings
warnings.filterwarnings('ignore')

print("Libraries imported successfully!")

"""## Download Data from GitHub"""

train_url = "https://raw.githubusercontent.com/AI-is-out-there/check-your-biomed-datascience-skills-review/main/dataset/task1/train.csv"
test_url = "https://raw.githubusercontent.com/AI-is-out-there/check-your-biomed-datascience-skills-review/main/dataset/task1/test_features.csv"

print("Downloading training data...")
train_df = pd.read_csv(train_url)
print(f"Training data loaded: {train_df.shape}")

print("Downloading test data...")
test_df = pd.read_csv(test_url)
print(f"Test data loaded: {test_df.shape}")

"""## Explore the Data"""

print("Training data columns:")
print(train_df.columns.tolist())

print("\nFirst few rows of training data:")
display(train_df.head())

print("\nTarget distribution:")
print(train_df['prediction'].value_counts())
print(f"\nTarget percentage:")
print(train_df['prediction'].value_counts(normalize=True) * 100)

"""## Data Preprocessing"""

feature_cols = [
    'Возраст', 'ИМТ', 'Окружность_талии_см', 'САД_мм_рт_ст',
    'ДАД_мм_рт_ст', 'Глюкоза_натощак_ммоль_л', 'HbA1c_%',
    'ЛПНП_ммоль_л', 'Триглицериды_ммоль_л', 'СКФ_мл_мин',
    'Курение', 'Статус_глюкозы', 'Доклинический_риск'
]

for col in feature_cols:
    if col in train_df.columns:
        median_val = train_df[col].median()
        train_df[col] = train_df[col].fillna(median_val)
        test_df[col] = test_df[col].fillna(median_val)

print("Missing values handled")
print(f"\nMissing values remaining in training data: {train_df[feature_cols].isnull().sum().sum()}")
print(f"Missing values remaining in test data: {test_df[feature_cols].isnull().sum().sum()}")

"""## Rule-Based Classification Function"""

def predict_risk(row):
    """
    Risk-based prediction using medical thresholds
    Returns 1 for high risk, 0 for low risk
    """
    risk_score = 0

    if row['Возраст'] > 55:
        risk_score += 1

    if row['ИМТ'] > 30:
        risk_score += 1

    if row['Окружность_талии_см'] > 90:
        risk_score += 1

    if row['САД_мм_рт_ст'] > 140 or row['ДАД_мм_рт_ст'] > 90:
        risk_score += 1

    if row['Глюкоза_натощак_ммоль_л'] > 5.6:
        risk_score += 2

    if row['HbA1c_%'] > 5.7:
        risk_score += 2

    if row['ЛПНП_ммоль_л'] > 3.0:
        risk_score += 1

    if row['Триглицериды_ммоль_л'] > 1.7:
        risk_score += 1

    if row['СКФ_мл_мин'] < 60:
        risk_score += 1

    if row['Курение'] == 1:
        risk_score += 1

    if row['Статус_глюкозы'] > 0:
        risk_score += 2

    if row['Доклинический_риск'] > 0:
        risk_score += 1

    return 1 if risk_score >= 4 else 0

print("Risk prediction function defined")

"""## Validate on Training Data"""

train_predictions = train_df.apply(predict_risk, axis=1)

train_accuracy = (train_predictions == train_df['prediction']).mean()
print(f"Rule-based classifier training accuracy: {train_accuracy:.4f}")

print("\nPrediction vs Actual:")
comparison = pd.DataFrame({
    'actual': train_df['prediction'],
    'predicted': train_predictions
})
print(comparison.value_counts())

print("\nPer-class accuracy:")
for actual_class in [0, 1]:
    mask = train_df['prediction'] == actual_class
    class_accuracy = (train_predictions[mask] == train_df['prediction'][mask]).mean()
    print(f"Class {actual_class}: {class_accuracy:.4f}")

"""## Generate Test Predictions"""

test_predictions = test_df.apply(predict_risk, axis=1)

submission = pd.DataFrame({
    'patient_id': test_df['patient_id'],
    'prediction': test_predictions
})

print(f"Prediction distribution:")
print(submission['prediction'].value_counts())
print(f"\nPrediction percentage:")
print(submission['prediction'].value_counts(normalize=True) * 100)

print(f"\nFirst few predictions:")
display(submission.head(10))

"""## Download Results"""

submission.to_csv('task1_predictions.csv', index=False)

print("Predictions saved to: task1_predictions.csv")
print(f"Total predictions: {len(submission)}")
print(f"Missing values: {submission.isnull().sum().sum()}")

